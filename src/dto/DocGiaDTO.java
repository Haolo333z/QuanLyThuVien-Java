package dto;

import java.time.LocalDate;

public class DocGiaDTO {
    private int maDocGia;
    private String hoTen;
    private LocalDate ngaySinh;
    private String gioiTinh;
    private String soDienThoai;
    private String email;
    private String diaChi;
    private LocalDate ngayLapThe;
    private LocalDate ngayHetHan;
    private boolean trangThai;

    public DocGiaDTO() {
    }

    public DocGiaDTO(int maDocGia, String hoTen, LocalDate ngaySinh, String gioiTinh,
                     String soDienThoai, String email, String diaChi,
                     LocalDate ngayLapThe, LocalDate ngayHetHan, boolean trangThai) {
        this.maDocGia = maDocGia;
        this.hoTen = hoTen;
        this.ngaySinh = ngaySinh;
        this.gioiTinh = gioiTinh;
        this.soDienThoai = soDienThoai;
        this.email = email;
        this.diaChi = diaChi;
        this.ngayLapThe = ngayLapThe;
        this.ngayHetHan = ngayHetHan;
        this.trangThai = trangThai;
    }

    public int getMaDocGia() { return maDocGia; }
    public void setMaDocGia(int maDocGia) { this.maDocGia = maDocGia; }

    public String getHoTen() { return hoTen; }
    public void setHoTen(String hoTen) { this.hoTen = hoTen; }

    public LocalDate getNgaySinh() { return ngaySinh; }
    public void setNgaySinh(LocalDate ngaySinh) { this.ngaySinh = ngaySinh; }

    public String getGioiTinh() { return gioiTinh; }
    public void setGioiTinh(String gioiTinh) { this.gioiTinh = gioiTinh; }

    public String getSoDienThoai() { return soDienThoai; }
    public void setSoDienThoai(String soDienThoai) { this.soDienThoai = soDienThoai; }

    public String getEmail() { return email; }
    public void setEmail(String email) { this.email = email; }

    public String getDiaChi() { return diaChi; }
    public void setDiaChi(String diaChi) { this.diaChi = diaChi; }

    public LocalDate getNgayLapThe() { return ngayLapThe; }
    public void setNgayLapThe(LocalDate ngayLapThe) { this.ngayLapThe = ngayLapThe; }

    public LocalDate getNgayHetHan() { return ngayHetHan; }
    public void setNgayHetHan(LocalDate ngayHetHan) { this.ngayHetHan = ngayHetHan; }

    public boolean isTrangThai() { return trangThai; }
    public void setTrangThai(boolean trangThai) { this.trangThai = trangThai; }
}